//! Built-in database GUI: Adminer served as `adminer.<tld>`.
//!
//! The release file is fetched from github.com/vrana/adminer and verified
//! against the SHA-256 digest GitHub records for the asset. A small wrapper
//! allows passwordless logins, which Corral's local MySQL/PostgreSQL use;
//! the site is only reachable from this Mac (127.0.0.1).

use anyhow::Context;
use corral_core::paths::Paths;
use std::path::PathBuf;

pub fn dir(paths: &Paths) -> PathBuf {
    paths.root.join("adminer")
}

pub fn installed(paths: &Paths) -> bool {
    dir(paths).join("adminer.php").is_file()
}

const WRAPPER: &str = r#"<?php
// Generated by Corral. Lets Adminer log in to Corral's passwordless local
// databases (MySQL root, PostgreSQL trust auth). Only reachable on 127.0.0.1.
function adminer_object() {
    if (class_exists('Adminer\Adminer')) {
        class CorralAdminer extends \Adminer\Adminer {
            function name() { return 'Corral Adminer'; }
            function login($login, $password) { return true; }
        }
        return new CorralAdminer();
    }
    return null;
}
require __DIR__ . '/adminer.php';
"#;

/// Download (or update) Adminer. Returns the installed version tag.
pub async fn install(paths: &Paths) -> anyhow::Result<String> {
    let api = "https://api.github.com/repos/vrana/adminer/releases/latest";
    let body = corral_fetch::client()?
        .get(api)
        .header("Accept", "application/vnd.github+json")
        .send()
        .await?
        .error_for_status()?
        .text()
        .await?;
    let rel: serde_json::Value = serde_json::from_str(&body)?;
    let tag = rel["tag_name"]
        .as_str()
        .context("release has no tag")?
        .to_string();
    let want = format!("adminer-{}.php", tag.trim_start_matches('v'));
    let asset = rel["assets"]
        .as_array()
        .and_then(|a| a.iter().find(|x| x["name"] == want.as_str()))
        .with_context(|| format!("{want} missing from the release"))?;
    let url = asset["browser_download_url"]
        .as_str()
        .context("asset url")?;
    let digest = asset["digest"]
        .as_str()
        .and_then(|d| d.strip_prefix("sha256:"))
        .context("GitHub did not report a SHA-256 for the asset")?;
    let expected = corral_fetch::Expected {
        algo: corral_fetch::Hash::Sha256,
        hex: digest.into(),
    };
    let file = corral_fetch::fetch_verified(url, &paths.downloads_dir(), Some(&expected)).await?;
    let d = dir(paths);
    std::fs::create_dir_all(&d)?;
    std::fs::rename(&file, d.join("adminer.php"))?;
    std::fs::write(d.join("index.php"), WRAPPER)?;
    std::fs::write(d.join("VERSION"), &tag)?;
    Ok(tag)
}

pub fn remove(paths: &Paths) -> std::io::Result<()> {
    let d = dir(paths);
    if d.exists() {
        std::fs::remove_dir_all(d)?;
    }
    Ok(())
}
