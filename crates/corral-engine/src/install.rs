//! Runtime installers (Caddy, PHP). Download/verify/extract live in `corral-fetch`.

use anyhow::{Context, bail};
use corral_core::paths::Paths;
use corral_core::php::PhpVersion;
pub use corral_fetch::{Expected, Hash, client, download, extract_entry, find_checksum, verify};
use std::path::PathBuf;

pub const CADDY_VERSION: &str = "2.11.9";

pub fn arch() -> &'static str {
    if cfg!(target_arch = "aarch64") {
        "arm64"
    } else {
        "amd64"
    }
}

pub fn tools_dir(paths: &Paths) -> PathBuf {
    paths.root.join("tools")
}

pub fn caddy_bin(paths: &Paths) -> PathBuf {
    tools_dir(paths).join("caddy")
}

/// Install Caddy from the official GitHub release, verified against the
/// release's SHA-512 checksum file.
pub async fn install_caddy(paths: &Paths) -> anyhow::Result<PathBuf> {
    let v = CADDY_VERSION;
    let file = format!("caddy_{v}_mac_{}.tar.gz", arch());
    let base = format!("https://github.com/caddyserver/caddy/releases/download/v{v}");
    let sums = client()?
        .get(format!("{base}/caddy_{v}_checksums.txt"))
        .send()
        .await?
        .error_for_status()?
        .text()
        .await?;
    let expected = Expected {
        algo: Hash::Sha512,
        hex: find_checksum(&sums, &file)
            .with_context(|| format!("{file} missing from checksums"))?,
    };
    let url = format!("{base}/{file}");
    let archive = paths.downloads_dir().join(&file);
    let (s256, s512) = download(&url, &archive).await?;
    verify((&s256, &s512), Some(&expected), &url)?;
    let bin = caddy_bin(paths);
    extract_entry(&archive, "caddy", &bin)?;
    std::fs::remove_file(&archive).ok();
    Ok(bin)
}

pub fn composer_phar(paths: &Paths) -> PathBuf {
    tools_dir(paths).join("composer.phar")
}

/// Install the latest stable Composer, verified against its published
/// SHA-256, plus a `composer` shim that runs it with Corral's default PHP.
pub async fn install_composer(paths: &Paths) -> anyhow::Result<PathBuf> {
    let base = "https://getcomposer.org/download/latest-stable";
    let sum = client()?
        .get(format!("{base}/composer.phar.sha256sum"))
        .send()
        .await?
        .error_for_status()?
        .text()
        .await?;
    let hex = sum
        .split_whitespace()
        .next()
        .filter(|h| h.len() == 64)
        .context("unexpected composer checksum format")?;
    let expected = Expected {
        algo: Hash::Sha256,
        hex: hex.into(),
    };
    let phar = corral_fetch::fetch_verified(
        &format!("{base}/composer.phar"),
        &paths.downloads_dir(),
        Some(&expected),
    )
    .await?;
    let dest = composer_phar(paths);
    std::fs::create_dir_all(tools_dir(paths))?;
    std::fs::rename(&phar, &dest)?;
    write_composer_shim(paths)?;
    Ok(dest)
}

pub fn write_composer_shim(paths: &Paths) -> std::io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    let shim = paths.bin.join("composer");
    let body = format!(
        "#!/bin/sh\n# Generated by Corral.\nexec \"{}\" \"{}\" \"$@\"\n",
        paths.bin.join("php").display(),
        composer_phar(paths).display()
    );
    corral_core::fsutil::write_if_changed(&shim, body.as_bytes())?;
    std::fs::set_permissions(&shim, std::fs::Permissions::from_mode(0o755))
}

/// One file in a PHP build manifest.
#[derive(Debug, Clone, PartialEq, Eq, serde::Deserialize, serde::Serialize)]
pub struct ManifestFile {
    pub url: String,
    pub sha256: String,
}

/// A PHP build for one version and CPU.
#[derive(Debug, Clone, PartialEq, Eq, serde::Deserialize, serde::Serialize)]
pub struct ManifestBuild {
    /// Full version, e.g. `8.4.23`.
    pub version: String,
    /// `arm64` or `x86_64`.
    pub arch: String,
    pub cli: ManifestFile,
    pub fpm: ManifestFile,
    /// tar.gz containing `xdebug.so` built for this exact PHP.
    #[serde(default)]
    pub xdebug: Option<ManifestFile>,
}

/// Corral's PHP build manifest (published next to the CI-built archives).
#[derive(Debug, Clone, PartialEq, Eq, serde::Deserialize, serde::Serialize)]
pub struct Manifest {
    pub schema: u32,
    pub php: Vec<ManifestBuild>,
}

impl Manifest {
    pub fn parse(json: &str) -> anyhow::Result<Self> {
        let m: Manifest = serde_json::from_str(json)?;
        anyhow::ensure!(m.schema == 1, "unsupported manifest schema {}", m.schema);
        for b in &m.php {
            for f in [Some(&b.cli), Some(&b.fpm), b.xdebug.as_ref()]
                .into_iter()
                .flatten()
            {
                anyhow::ensure!(
                    f.url.starts_with("https://") && f.sha256.len() == 64,
                    "manifest entry for {} has an insecure URL or bad digest",
                    b.version
                );
            }
        }
        Ok(m)
    }

    /// Newest build of `minor` for this CPU.
    pub fn pick(&self, minor: PhpVersion) -> Option<&ManifestBuild> {
        let arch = if cfg!(target_arch = "aarch64") {
            "arm64"
        } else {
            "x86_64"
        };
        let key = |v: &str| -> Vec<u32> { v.split('.').filter_map(|p| p.parse().ok()).collect() };
        self.php
            .iter()
            .filter(|b| b.arch == arch && PhpVersion::parse(&b.version) == Some(minor))
            .max_by(|a, b| key(&a.version).cmp(&key(&b.version)))
    }
}

/// Load a manifest from an https URL or a local file.
pub async fn load_manifest(src: &str) -> anyhow::Result<Manifest> {
    let body = if src.starts_with("https://") {
        client()?
            .get(src)
            .send()
            .await?
            .error_for_status()?
            .text()
            .await?
    } else if src.starts_with("http://") {
        bail!("refusing to load a PHP manifest over plain http");
    } else {
        std::fs::read_to_string(src).with_context(|| format!("read {src}"))?
    };
    Manifest::parse(&body)
}

/// Install a manifest build (all files checksum-verified), including
/// xdebug.so when the build ships one.
pub async fn install_php_from_manifest(
    paths: &Paths,
    b: &ManifestBuild,
) -> anyhow::Result<PathBuf> {
    let v = PhpVersion::parse(&b.version).context("bad version in manifest")?;
    let src = PhpSource {
        cli_url: b.cli.url.clone(),
        fpm_url: b.fpm.url.clone(),
        cli_sha256: Some(b.cli.sha256.clone()),
        fpm_sha256: Some(b.fpm.sha256.clone()),
    };
    let dir = install_php(paths, v, &src, false).await?;
    if let Some(x) = &b.xdebug {
        let exp = Expected {
            algo: Hash::Sha256,
            hex: x.sha256.clone(),
        };
        let archive =
            corral_fetch::fetch_verified(&x.url, &paths.downloads_dir(), Some(&exp)).await?;
        extract_entry(&archive, "xdebug.so", &dir.join("lib/xdebug.so"))?;
        std::fs::remove_file(&archive).ok();
    }
    Ok(dir)
}

/// Where a PHP build comes from.
#[derive(Debug, Clone)]
pub struct PhpSource {
    pub cli_url: String,
    pub fpm_url: String,
    pub cli_sha256: Option<String>,
    pub fpm_sha256: Option<String>,
}

impl PhpSource {
    /// Upstream static-php-cli "common" builds. They publish no checksums, so
    /// installing from here requires `allow_unverified` until Corral hosts its
    /// own signed manifest (PLAN 0.5).
    pub fn static_php(full_version: &str) -> Self {
        let a = if cfg!(target_arch = "aarch64") {
            "aarch64"
        } else {
            "x86_64"
        };
        let base = "https://dl.static-php.dev/static-php-cli/common";
        Self {
            cli_url: format!("{base}/php-{full_version}-cli-macos-{a}.tar.gz"),
            fpm_url: format!("{base}/php-{full_version}-fpm-macos-{a}.tar.gz"),
            cli_sha256: None,
            fpm_sha256: None,
        }
    }
}

/// Find the newest patch release of `minor` in the static-php index page.
pub async fn latest_static_php(minor: PhpVersion) -> anyhow::Result<String> {
    let html = client()?
        .get("https://dl.static-php.dev/static-php-cli/common/")
        .send()
        .await?
        .error_for_status()?
        .text()
        .await?;
    newest_patch(&html, minor).with_context(|| format!("no static build of PHP {minor} found"))
}

/// Pure helper for [`latest_static_php`].
pub fn newest_patch(index: &str, minor: PhpVersion) -> Option<String> {
    let prefix = format!("php-{minor}.");
    let mut best: Option<(u32, String)> = None;
    for part in index.split(&prefix).skip(1) {
        let patch: String = part.chars().take_while(char::is_ascii_digit).collect();
        if patch.is_empty() || !part[patch.len()..].starts_with("-fpm-macos-") {
            continue;
        }
        let n: u32 = patch.parse().ok()?;
        if best.as_ref().is_none_or(|(b, _)| n > *b) {
            best = Some((n, format!("{minor}.{n}")));
        }
    }
    best.map(|(_, v)| v)
}

pub async fn install_php(
    paths: &Paths,
    version: PhpVersion,
    src: &PhpSource,
    allow_unverified: bool,
) -> anyhow::Result<PathBuf> {
    if !allow_unverified && (src.cli_sha256.is_none() || src.fpm_sha256.is_none()) {
        bail!(
            "refusing to install PHP {version} without checksums (pass --allow-unverified to override)"
        );
    }
    let dir = paths.php_version_dir(&version.to_string());
    for (url, sha, entry, dest) in [
        (&src.cli_url, &src.cli_sha256, "php", dir.join("bin/php")),
        (
            &src.fpm_url,
            &src.fpm_sha256,
            "php-fpm",
            dir.join("sbin/php-fpm"),
        ),
    ] {
        let name = url.rsplit('/').next().unwrap_or("php.tar.gz");
        let archive = paths.downloads_dir().join(name);
        let (s256, s512) = download(url, &archive).await?;
        let exp = sha.as_ref().map(|h| Expected {
            algo: Hash::Sha256,
            hex: h.clone(),
        });
        verify((&s256, &s512), exp.as_ref(), url)?;
        extract_entry(&archive, entry, &dest)?;
        std::fs::remove_file(&archive).ok();
    }
    Ok(dir)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn manifest_parse_validate_and_pick() {
        let arch = if cfg!(target_arch = "aarch64") {
            "arm64"
        } else {
            "x86_64"
        };
        let f = |n: &str| {
            format!(
                r#"{{"url":"https://example.test/{n}","sha256":"{}"}}"#,
                "a".repeat(64)
            )
        };
        let json = format!(
            r#"{{"schema":1,"php":[
              {{"version":"8.4.9","arch":"{arch}","cli":{c},"fpm":{c}}},
              {{"version":"8.4.23","arch":"{arch}","cli":{c},"fpm":{c},"xdebug":{c}}},
              {{"version":"8.4.99","arch":"other","cli":{c},"fpm":{c}}}
            ]}}"#,
            c = f("x.tar.gz")
        );
        let m = Manifest::parse(&json).unwrap();
        let b = m.pick(PhpVersion::parse("8.4").unwrap()).unwrap();
        assert_eq!(b.version, "8.4.23");
        assert!(b.xdebug.is_some());
        assert!(m.pick(PhpVersion::parse("8.3").unwrap()).is_none());
        let insecure = json.replace("https://", "http://");
        assert!(Manifest::parse(&insecure).is_err());
        assert!(Manifest::parse(r#"{"schema":2,"php":[]}"#).is_err());
    }

    #[test]
    fn finds_newest_patch() {
        let idx = r#"<a href="php-8.4.9-fpm-macos-aarch64.tar.gz"> <a href="php-8.4.23-cli-macos-aarch64.tar.gz">
            <a href="php-8.4.23-fpm-macos-aarch64.tar.gz"> <a href="php-8.4.100-cli-linux.tar.gz">
            <a href="php-8.5.1-fpm-macos-aarch64.tar.gz">"#;
        let v = PhpVersion::parse("8.4").unwrap();
        assert_eq!(newest_patch(idx, v).as_deref(), Some("8.4.23"));
        assert_eq!(newest_patch(idx, PhpVersion::parse("7.4").unwrap()), None);
    }

    #[tokio::test]
    async fn php_install_requires_checksums_unless_opted_out() {
        let t = tempfile::tempdir().unwrap();
        let p = Paths::at(t.path());
        let src = PhpSource::static_php("8.4.23");
        let err = install_php(&p, PhpVersion::parse("8.4").unwrap(), &src, false)
            .await
            .unwrap_err();
        assert!(err.to_string().contains("without checksums"));
    }
}
