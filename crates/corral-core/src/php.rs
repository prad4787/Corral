//! PHP versions: discovery of installed runtimes, FPM pool configuration and
//! PATH shims.
//!
//! Layout per version (`php/<major.minor>/`):
//!
//! ```text
//! bin/php            CLI binary
//! sbin/php-fpm       FPM binary
//! etc/php.ini        generated base ini (owned by Corral, regenerated)
//! etc/conf.d/*.ini   user overrides (never touched by Corral)
//! ```

use crate::fsutil::write_atomic;
use crate::paths::Paths;
use std::path::PathBuf;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct PhpVersion {
    pub major: u8,
    pub minor: u8,
}

impl PhpVersion {
    pub fn parse(s: &str) -> Option<Self> {
        let s = s.trim().trim_start_matches("php").trim_start_matches('@');
        let mut it = s.split('.');
        let major = it.next()?.parse().ok()?;
        let minor = it.next()?.parse().ok()?;
        // Accept "8.4.3" but only keep major.minor.
        if it.next().is_some_and(|p| p.parse::<u16>().is_err()) {
            return None;
        }
        ((5..=9).contains(&major)).then_some(Self { major, minor })
    }
}

impl std::fmt::Display for PhpVersion {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}.{}", self.major, self.minor)
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Installation {
    pub version: PhpVersion,
    pub dir: PathBuf,
}

impl Installation {
    pub fn cli(&self) -> PathBuf {
        self.dir.join("bin/php")
    }
    pub fn fpm(&self) -> PathBuf {
        self.dir.join("sbin/php-fpm")
    }
    pub fn ini(&self) -> PathBuf {
        self.dir.join("etc/php.ini")
    }
    pub fn conf_d(&self) -> PathBuf {
        self.dir.join("etc/conf.d")
    }
    pub fn fpm_conf(&self) -> PathBuf {
        self.dir.join("etc/php-fpm.conf")
    }
}

/// All installed versions, newest first. A version counts as installed when
/// both the CLI and FPM binaries exist.
pub fn installed(paths: &Paths) -> std::io::Result<Vec<Installation>> {
    let mut out = Vec::new();
    let rd = match std::fs::read_dir(paths.php_dir()) {
        Ok(rd) => rd,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(out),
        Err(e) => return Err(e),
    };
    for ent in rd.flatten() {
        let Some(version) = ent.file_name().to_str().and_then(PhpVersion::parse) else {
            continue;
        };
        let inst = Installation {
            version,
            dir: ent.path(),
        };
        if inst.cli().is_file() && inst.fpm().is_file() {
            out.push(inst);
        }
    }
    out.sort_by(|a, b| b.version.cmp(&a.version));
    Ok(out)
}

pub fn find(paths: &Paths, version: PhpVersion) -> std::io::Result<Option<Installation>> {
    Ok(installed(paths)?.into_iter().find(|i| i.version == version))
}

/// Base `php.ini`. Opinionated development defaults; users override via conf.d.
pub fn base_ini(paths: &Paths, inst: &Installation, prepend: Option<&std::path::Path>) -> String {
    let mut ini = format!(
        r#"; Generated by Corral. Do not edit: put overrides in {conf_d}
memory_limit = 512M
upload_max_filesize = 512M
post_max_size = 512M
max_execution_time = 120
display_errors = On
display_startup_errors = On
; Deprecations from vendor code flood logs on new PHP versions; frameworks
; set their own level at runtime. Override in conf.d if you want them.
error_reporting = E_ALL & ~E_DEPRECATED
log_errors = On
error_log = {log}
date.timezone = UTC
opcache.enable = 1
opcache.enable_cli = 0
opcache.validate_timestamps = 1
opcache.revalidate_freq = 0
"#,
        conf_d = inst.conf_d().display(),
        log = paths
            .logs_dir()
            .join(format!("php-{}.log", inst.version))
            .display(),
    );
    if let Some(p) = prepend {
        ini.push_str(&format!(
            "; Corral dump viewer (disable with `dumps = false` in config.toml)\nauto_prepend_file = \"{}\"\n",
            p.display()
        ));
    }
    ini
}

/// FPM master + single pool listening on a unix socket owned by the user.
pub fn fpm_conf(paths: &Paths, inst: &Installation) -> String {
    let v = inst.version;
    format!(
        r#"; Generated by Corral.
[global]
pid = {pid}
error_log = {log}
daemonize = no

[corral]
listen = {sock}
listen.mode = 0600
pm = dynamic
pm.max_children = 16
pm.start_servers = 2
pm.min_spare_servers = 1
pm.max_spare_servers = 4
pm.max_requests = 500
catch_workers_output = yes
decorate_workers_output = no
clear_env = no
"#,
        pid = paths.run_dir().join(format!("php-fpm-{v}.pid")).display(),
        log = paths.logs_dir().join(format!("php-fpm-{v}.log")).display(),
        sock = paths.fpm_socket(&v.to_string()).display(),
    )
}

/// Xdebug for this version, when the build ships one (Corral's own builds do).
pub fn xdebug_so(inst: &Installation) -> PathBuf {
    inst.dir.join("lib/xdebug.so")
}

pub fn xdebug_available(inst: &Installation) -> bool {
    xdebug_so(inst).is_file()
}

pub fn fpm_debug_conf_path(inst: &Installation) -> PathBuf {
    inst.dir.join("etc/php-fpm-debug.conf")
}

/// A second, small pool with Xdebug loaded. Only Xdebug-triggered requests
/// are routed here, so normal requests keep full speed.
pub fn fpm_debug_conf(paths: &Paths, inst: &Installation) -> String {
    let v = inst.version;
    format!(
        r#"; Generated by Corral.
[global]
pid = {pid}
error_log = {log}
daemonize = no

[corral-debug]
listen = {sock}
listen.mode = 0600
pm = ondemand
pm.max_children = 4
pm.process_idle_timeout = 60s
catch_workers_output = yes
decorate_workers_output = no
clear_env = no
; Debugging sessions can sit on a breakpoint for a long time.
request_terminate_timeout = 0
"#,
        pid = paths
            .run_dir()
            .join(format!("php-fpm-{v}-debug.pid"))
            .display(),
        log = paths
            .logs_dir()
            .join(format!("php-fpm-{v}-debug.log"))
            .display(),
        sock = paths.fpm_debug_socket(&v.to_string()).display(),
    )
}

/// Arguments for the debug pool: the normal ini plus Xdebug settings.
pub fn fpm_debug_args(inst: &Installation) -> Vec<String> {
    let mut a = vec![
        "--nodaemonize".into(),
        "--fpm-config".into(),
        fpm_debug_conf_path(inst).display().to_string(),
        "-c".into(),
        inst.ini().display().to_string(),
    ];
    for d in [
        format!("zend_extension={}", xdebug_so(inst).display()),
        "xdebug.mode=debug,develop".into(),
        "xdebug.start_with_request=trigger".into(),
        "xdebug.client_host=127.0.0.1".into(),
        "xdebug.client_port=9003".into(),
        "max_execution_time=0".into(),
    ] {
        a.push("-d".into());
        a.push(d);
    }
    a
}

/// Write the generated ini + fpm config for an installation. Idempotent.
/// Returns true when either file changed, i.e. a running pool must restart.
pub fn write_configs(
    paths: &Paths,
    inst: &Installation,
    prepend: Option<&std::path::Path>,
) -> std::io::Result<bool> {
    use crate::fsutil::write_if_changed;
    std::fs::create_dir_all(inst.conf_d())?;
    let ini = write_if_changed(&inst.ini(), base_ini(paths, inst, prepend).as_bytes())?;
    let fpm = write_if_changed(&inst.fpm_conf(), fpm_conf(paths, inst).as_bytes())?;
    let dbg = if xdebug_available(inst) {
        write_if_changed(
            &fpm_debug_conf_path(inst),
            fpm_debug_conf(paths, inst).as_bytes(),
        )?
    } else {
        false
    };
    Ok(ini || fpm || dbg)
}

/// The user-editable override file for a version (created on demand).
pub fn user_ini(inst: &Installation) -> std::path::PathBuf {
    inst.conf_d().join("90-user.ini")
}

/// Set (or with `None`, remove) one `key = value` in the user override file.
pub fn set_user_ini(inst: &Installation, key: &str, value: Option<&str>) -> std::io::Result<()> {
    let valid = !key.is_empty()
        && key
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'.' || b == b'_');
    if !valid {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidInput,
            format!("invalid ini key {key:?}"),
        ));
    }
    if value.is_some_and(|v| v.contains('\n')) {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidInput,
            "ini values must be a single line",
        ));
    }
    let path = user_ini(inst);
    let old = std::fs::read_to_string(&path)
        .unwrap_or_else(|_| "; Your PHP overrides. Corral never rewrites other lines.\n".into());
    let mut lines: Vec<String> = old
        .lines()
        .filter(|l| l.split('=').next().map(str::trim) != Some(key))
        .map(str::to_owned)
        .collect();
    if let Some(v) = value {
        lines.push(format!("{key} = {v}"));
    }
    let mut body = lines.join("\n");
    body.push('\n');
    std::fs::create_dir_all(inst.conf_d())?;
    write_atomic(&path, body.as_bytes())
}

/// Command-line arguments to run FPM in the foreground under the supervisor.
pub fn fpm_args(inst: &Installation) -> Vec<String> {
    vec![
        "--nodaemonize".into(),
        "--fpm-config".into(),
        inst.fpm_conf().display().to_string(),
        "-c".into(),
        inst.ini().display().to_string(),
    ]
}

/// Environment for any PHP process Corral starts: makes conf.d overrides apply.
pub fn php_env(inst: &Installation) -> Vec<(String, String)> {
    vec![(
        "PHP_INI_SCAN_DIR".into(),
        inst.conf_d().display().to_string(),
    )]
}

/// Write PATH shims: `php` (default), and `php8.4`-style versioned shims.
///
/// Shims are tiny shell scripts so they can set `PHP_INI_SCAN_DIR` and the ini path.
pub fn write_shims(paths: &Paths, default: Option<PhpVersion>) -> std::io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::create_dir_all(&paths.bin)?;
    let insts = installed(paths)?;

    let shim = |inst: &Installation| {
        format!(
            "#!/bin/sh\n# Generated by Corral.\nPHP_INI_SCAN_DIR=\"{}\" exec \"{}\" -c \"{}\" \"$@\"\n",
            inst.conf_d().display(),
            inst.cli().display(),
            inst.ini().display()
        )
    };
    let write = |name: &str, body: String| -> std::io::Result<()> {
        let p = paths.bin.join(name);
        write_atomic(&p, body.as_bytes())?;
        std::fs::set_permissions(&p, std::fs::Permissions::from_mode(0o755))
    };

    // Remove stale versioned shims for versions no longer installed.
    for ent in std::fs::read_dir(&paths.bin)?.flatten() {
        let n = ent.file_name().to_string_lossy().to_string();
        if let Some(v) = n.strip_prefix("php").and_then(PhpVersion::parse)
            && !insts.iter().any(|i| i.version == v)
        {
            std::fs::remove_file(ent.path())?;
        }
    }
    for inst in &insts {
        write(&format!("php{}", inst.version), shim(inst))?;
    }
    let default_inst = default
        .and_then(|d| insts.iter().find(|i| i.version == d))
        .or(insts.first());
    match default_inst {
        Some(inst) => write("php", shim(inst)),
        None => match std::fs::remove_file(paths.bin.join("php")) {
            Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(e),
            _ => Ok(()),
        },
    }
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;

    /// Create a fake installation with stub binaries.
    pub fn fake_install(paths: &Paths, v: &str) -> Installation {
        let dir = paths.php_version_dir(v);
        for b in ["bin/php", "sbin/php-fpm"] {
            let p = dir.join(b);
            std::fs::create_dir_all(p.parent().unwrap()).unwrap();
            std::fs::write(p, "#!/bin/sh\n").unwrap();
        }
        Installation {
            version: PhpVersion::parse(v).unwrap(),
            dir,
        }
    }

    #[test]
    fn debug_pool_only_with_xdebug() {
        let t = tempfile::tempdir().unwrap();
        let p = Paths::at(t.path());
        let i = fake_install(&p, "8.4");
        write_configs(&p, &i, None).unwrap();
        assert!(!xdebug_available(&i));
        assert!(!fpm_debug_conf_path(&i).exists());
        std::fs::create_dir_all(i.dir.join("lib")).unwrap();
        std::fs::write(xdebug_so(&i), "").unwrap();
        assert!(write_configs(&p, &i, None).unwrap());
        let c = std::fs::read_to_string(fpm_debug_conf_path(&i)).unwrap();
        assert!(c.contains(&format!("listen = {}", p.fpm_debug_socket("8.4").display())));
        let args = fpm_debug_args(&i).join(" ");
        assert!(
            args.contains("zend_extension=") && args.contains("xdebug.start_with_request=trigger")
        );
    }

    #[test]
    fn user_ini_set_replace_remove() {
        let t = tempfile::tempdir().unwrap();
        let p = Paths::at(t.path());
        let i = fake_install(&p, "8.4");
        set_user_ini(&i, "memory_limit", Some("1G")).unwrap();
        set_user_ini(&i, "xdebug.mode", Some("debug")).unwrap();
        set_user_ini(&i, "memory_limit", Some("2G")).unwrap();
        let s = std::fs::read_to_string(user_ini(&i)).unwrap();
        assert_eq!(s.matches("memory_limit").count(), 1);
        assert!(s.contains("memory_limit = 2G") && s.contains("xdebug.mode = debug"));
        set_user_ini(&i, "memory_limit", None).unwrap();
        assert!(
            !std::fs::read_to_string(user_ini(&i))
                .unwrap()
                .contains("memory_limit")
        );
        assert!(set_user_ini(&i, "bad key", Some("1")).is_err());
        assert!(set_user_ini(&i, "k", Some("a\nevil=1")).is_err());
    }

    #[test]
    fn parse_versions() {
        assert_eq!(
            PhpVersion::parse("8.4"),
            Some(PhpVersion { major: 8, minor: 4 })
        );
        assert_eq!(
            PhpVersion::parse("php@8.3"),
            Some(PhpVersion { major: 8, minor: 3 })
        );
        assert_eq!(PhpVersion::parse("8.2.27").unwrap().to_string(), "8.2");
        assert_eq!(PhpVersion::parse("php8.1").unwrap().to_string(), "8.1");
        assert_eq!(PhpVersion::parse("8"), None);
        assert_eq!(PhpVersion::parse("8.x"), None);
        assert_eq!(PhpVersion::parse("8.4.fpm"), None);
        assert_eq!(PhpVersion::parse("42.0"), None);
    }

    #[test]
    fn discovers_installed_newest_first() {
        let t = tempfile::tempdir().unwrap();
        let p = Paths::at(t.path());
        fake_install(&p, "8.2");
        fake_install(&p, "8.4");
        std::fs::create_dir_all(p.php_version_dir("8.3/bin")).unwrap(); // incomplete
        let v: Vec<_> = installed(&p)
            .unwrap()
            .iter()
            .map(|i| i.version.to_string())
            .collect();
        assert_eq!(v, ["8.4", "8.2"]);
    }

    #[test]
    fn configs_reference_socket_and_conf_d() {
        let t = tempfile::tempdir().unwrap();
        let p = Paths::at(t.path());
        let i = fake_install(&p, "8.4");
        assert!(
            write_configs(&p, &i, None).unwrap(),
            "first write changes files"
        );
        assert!(
            !write_configs(&p, &i, None).unwrap(),
            "second write is a no-op"
        );
        assert!(
            !std::fs::read_to_string(i.ini())
                .unwrap()
                .contains("auto_prepend_file")
        );
        let pre = std::path::Path::new("/x/corral-prepend.php");
        assert!(
            write_configs(&p, &i, Some(pre)).unwrap(),
            "enabling dumps changes the ini"
        );
        assert!(
            std::fs::read_to_string(i.ini())
                .unwrap()
                .contains("auto_prepend_file = \"/x/corral-prepend.php\"")
        );
        let ini = std::fs::read_to_string(i.ini()).unwrap();
        assert!(ini.contains("error_reporting = E_ALL & ~E_DEPRECATED"));
        let fpm = std::fs::read_to_string(i.fpm_conf()).unwrap();
        assert!(fpm.contains(&format!("listen = {}", p.fpm_socket("8.4").display())));
        assert!(fpm.contains("daemonize = no"));
        assert!(i.conf_d().is_dir());
    }

    #[test]
    fn shims_follow_default_and_clean_up() {
        let t = tempfile::tempdir().unwrap();
        let p = Paths::at(t.path());
        let a = fake_install(&p, "8.2");
        fake_install(&p, "8.4");
        write_shims(&p, PhpVersion::parse("8.2")).unwrap();
        let php = std::fs::read_to_string(p.bin.join("php")).unwrap();
        assert!(php.contains(&a.cli().display().to_string()));
        assert!(p.bin.join("php8.4").exists());

        std::fs::remove_dir_all(p.php_version_dir("8.2")).unwrap();
        write_shims(&p, PhpVersion::parse("8.2")).unwrap();
        assert!(!p.bin.join("php8.2").exists());
        // Falls back to the newest installed version.
        assert!(
            std::fs::read_to_string(p.bin.join("php"))
                .unwrap()
                .contains("/8.4/")
        );
    }
}
