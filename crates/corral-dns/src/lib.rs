//! A tiny authoritative DNS server: every name under the local TLD resolves to
//! the loopback address. Replaces dnsmasq.
//!
//! macOS sends queries for `*.<tld>` here because the helper writes
//! `/etc/resolver/<tld>` with `nameserver 127.0.0.1` and `port <dns_port>`.
//! Anything outside the TLD is answered with REFUSED, so this server can never
//! be used as an open resolver.

use hickory_proto::op::{Message, MessageType, OpCode, Query, ResponseCode};
use hickory_proto::rr::rdata::A;
use hickory_proto::rr::{DNSClass, Name, RData, Record, RecordType};
use std::net::{Ipv4Addr, SocketAddr};
use tokio::net::UdpSocket;

const TTL: u32 = 60;

#[derive(Debug, Clone)]
pub struct Zone {
    origin: Name,
    address: Ipv4Addr,
}

impl Zone {
    pub fn new(tld: &str, address: Ipv4Addr) -> anyhow::Result<Self> {
        let mut origin = Name::from_ascii(tld)?;
        origin.set_fqdn(true);
        Ok(Self {
            origin: origin.to_lowercase(),
            address,
        })
    }

    /// Build the response for a raw query packet. `None` means drop silently
    /// (unparseable input or a packet that is itself a response).
    pub fn answer(&self, packet: &[u8]) -> Option<Vec<u8>> {
        let req = Message::from_vec(packet).ok()?;
        if req.metadata.message_type != MessageType::Query {
            return None;
        }
        let id = req.metadata.id;
        if req.metadata.op_code != OpCode::Query || req.queries.len() != 1 {
            return Message::error_msg(id, req.metadata.op_code, ResponseCode::NotImp)
                .to_vec()
                .ok();
        }
        let q: &Query = &req.queries[0];
        let mut resp = Message::response(id, OpCode::Query);
        resp.metadata.recursion_desired = req.metadata.recursion_desired;
        resp.add_query(q.clone());

        let name = q.name().to_lowercase();
        if !self.origin.zone_of(&name) || q.query_class() != DNSClass::IN {
            resp.metadata.response_code = ResponseCode::Refused;
            return resp.to_vec().ok();
        }
        resp.metadata.authoritative = true;
        if matches!(q.query_type(), RecordType::A | RecordType::ANY) {
            resp.add_answer(Record::from_rdata(
                q.name().clone(),
                TTL,
                RData::A(A(self.address)),
            ));
        }
        // AAAA and everything else: NOERROR with no data. We deliberately do not
        // answer ::1 because the web server listens on IPv4 loopback only.
        resp.to_vec().ok()
    }
}

/// Bind the UDP socket. Separate from [`serve`] so callers can report bind errors early.
pub async fn bind(addr: SocketAddr) -> std::io::Result<UdpSocket> {
    UdpSocket::bind(addr).await
}

/// Serve forever on an already-bound socket.
pub async fn serve(socket: UdpSocket, zone: Zone) -> std::io::Result<()> {
    let mut buf = [0u8; 4096];
    loop {
        let (len, peer) = socket.recv_from(&mut buf).await?;
        if let Some(out) = zone.answer(&buf[..len]) {
            if let Err(e) = socket.send_to(&out, peer).await {
                tracing::debug!(%peer, error = %e, "dns reply failed");
            }
        }
    }
}

/// The contents of `/etc/resolver/<tld>` for this server.
pub fn resolver_file(port: u16) -> String {
    format!("# Generated by Corral\nnameserver 127.0.0.1\nport {port}\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn query(name: &str, rt: RecordType) -> Vec<u8> {
        let mut m = Message::query();
        m.metadata.id = 4242;
        m.metadata.recursion_desired = true;
        m.add_query(Query::query(Name::from_ascii(name).unwrap(), rt));
        m.to_vec().unwrap()
    }

    fn zone() -> Zone {
        Zone::new("test", Ipv4Addr::LOCALHOST).unwrap()
    }

    fn ask(name: &str, rt: RecordType) -> Message {
        Message::from_vec(&zone().answer(&query(name, rt)).unwrap()).unwrap()
    }

    #[test]
    fn answers_a_for_names_under_tld() {
        for n in ["blog.test.", "api.Blog.TEST.", "test."] {
            let r = ask(n, RecordType::A);
            assert_eq!(r.metadata.id, 4242);
            assert_eq!(r.metadata.response_code, ResponseCode::NoError, "{n}");
            assert!(r.metadata.authoritative);
            assert_eq!(r.answers.len(), 1, "{n}");
            assert_eq!(r.answers[0].data, RData::A(A(Ipv4Addr::LOCALHOST)));
        }
    }

    #[test]
    fn aaaa_is_empty_noerror() {
        let r = ask("blog.test.", RecordType::AAAA);
        assert_eq!(r.metadata.response_code, ResponseCode::NoError);
        assert!(r.answers.is_empty());
    }

    #[test]
    fn refuses_other_zones() {
        for n in ["example.com.", "nottest.", "test.com."] {
            let r = ask(n, RecordType::A);
            assert_eq!(r.metadata.response_code, ResponseCode::Refused, "{n}");
            assert!(r.answers.is_empty());
        }
    }

    #[test]
    fn ignores_garbage_and_responses() {
        assert!(zone().answer(b"\x00\x01garbage").is_none());
        let resp = Message::response(1, OpCode::Query).to_vec().unwrap();
        assert!(zone().answer(&resp).is_none());
    }

    #[tokio::test]
    async fn serves_over_udp() {
        let sock = bind("127.0.0.1:0".parse().unwrap()).await.unwrap();
        let addr = sock.local_addr().unwrap();
        tokio::spawn(serve(sock, zone()));
        let client = UdpSocket::bind("127.0.0.1:0").await.unwrap();
        client
            .send_to(&query("x.test.", RecordType::A), addr)
            .await
            .unwrap();
        let mut buf = [0u8; 512];
        let (n, _) = tokio::time::timeout(
            std::time::Duration::from_secs(2),
            client.recv_from(&mut buf),
        )
        .await
        .unwrap()
        .unwrap();
        let r = Message::from_vec(&buf[..n]).unwrap();
        assert_eq!(r.answers.len(), 1);
    }

    #[test]
    fn resolver_file_format() {
        assert_eq!(
            resolver_file(15353),
            "# Generated by Corral\nnameserver 127.0.0.1\nport 15353\n"
        );
    }
}
