//! MySQL Community Server: option file, data-directory initialization,
//! supervisor spec and database creation.
//!
//! Development defaults: listens on 127.0.0.1 only, `root` has no password
//! (matching Laravel's default `.env`), X Protocol is off so it never grabs
//! port 33060, and utf8mb4 is the server charset.

use crate::store::{self, Instance};
use anyhow::{Context, bail};
use corral_core::fsutil::write_if_changed;
use corral_core::paths::Paths;
use corral_supervisor::Spec;
use std::path::{Path, PathBuf};
use std::time::Duration;

fn q(p: &Path) -> String {
    // Option files accept double-quoted values; needed for "Application Support".
    format!("\"{}\"", p.display())
}

pub fn mysqld(dist: &Path) -> PathBuf {
    dist.join("bin/mysqld")
}
pub fn client(dist: &Path) -> PathBuf {
    dist.join("bin/mysql")
}

pub fn option_file(paths: &Paths, name: &str, inst: &Instance) -> String {
    let dist = store::dist_dir(paths, inst.kind, &inst.version);
    format!(
        "# Generated by Corral. Changes are overwritten.\n\
         [mysqld]\n\
         basedir={basedir}\n\
         datadir={datadir}\n\
         port={port}\n\
         bind-address=127.0.0.1\n\
         socket={sock}\n\
         pid-file={pid}\n\
         log-error={err}\n\
         mysqlx=OFF\n\
         character-set-server=utf8mb4\n\
         collation-server=utf8mb4_unicode_ci\n\
         max_allowed_packet=256M\n\
         skip-name-resolve\n\
         \n\
         [client]\n\
         socket={sock}\n\
         user=root\n",
        basedir = q(&dist),
        datadir = q(&store::data_dir(paths, name)),
        port = inst.port,
        sock = q(&store::socket(paths, name)),
        pid = q(&paths.run_dir().join(format!("{name}.pid"))),
        err = q(&paths.logs_dir().join(format!("service-{name}.err.log"))),
    )
}

/// Write the option file; true when it changed (the server must restart).
pub fn write_option_file(paths: &Paths, name: &str, inst: &Instance) -> std::io::Result<bool> {
    write_if_changed(
        &store::conf_file(paths, name),
        option_file(paths, name, inst).as_bytes(),
    )
}

fn defaults_arg(paths: &Paths, name: &str) -> String {
    format!(
        "--defaults-file={}",
        store::conf_file(paths, name).display()
    )
}

/// True once the data directory contains the system schema.
pub fn initialized(paths: &Paths, name: &str) -> bool {
    store::data_dir(paths, name).join("mysql.ibd").exists()
}

/// Create the data directory with `--initialize-insecure` if needed.
pub async fn ensure_initialized(paths: &Paths, name: &str, inst: &Instance) -> anyhow::Result<()> {
    write_option_file(paths, name, inst)?;
    if initialized(paths, name) {
        return Ok(());
    }
    let data = store::data_dir(paths, name);
    // mysqld refuses to initialize into a non-empty directory.
    if data.exists() && std::fs::read_dir(&data)?.next().is_some() {
        bail!(
            "data directory {} exists but is not an initialized MySQL datadir; move it away first",
            data.display()
        );
    }
    std::fs::create_dir_all(paths.logs_dir())?;
    std::fs::create_dir_all(paths.run_dir())?;
    // mysqld accepts an existing empty datadir but will not create parents.
    std::fs::create_dir_all(&data)?;
    let dist = store::dist_dir(paths, inst.kind, &inst.version);
    tracing::info!(service = name, "initializing MySQL data directory");
    let out = tokio::process::Command::new(mysqld(&dist))
        .arg(defaults_arg(paths, name))
        .arg("--initialize-insecure")
        .output()
        .await
        .with_context(|| format!("run {}", mysqld(&dist).display()))?;
    if !out.status.success() || !initialized(paths, name) {
        let log = std::fs::read_to_string(paths.logs_dir().join(format!("service-{name}.err.log")))
            .unwrap_or_default();
        let tail: Vec<&str> = log.lines().rev().take(8).collect();
        bail!(
            "MySQL initialization failed ({}):\n{}",
            out.status,
            tail.into_iter().rev().collect::<Vec<_>>().join("\n")
        );
    }
    Ok(())
}

pub fn spec(paths: &Paths, name: &str, inst: &Instance) -> Spec {
    let dist = store::dist_dir(paths, inst.kind, &inst.version);
    let mut s = Spec::new(
        store::unit(name),
        mysqld(&dist),
        store::log_file(paths, name),
    )
    .args([defaults_arg(paths, name)]);
    // InnoDB needs time to flush on shutdown; never SIGKILL it early.
    s.stop_timeout = Duration::from_secs(60);
    s
}

/// Valid MySQL identifier for `CREATE DATABASE` (we only allow a safe subset).
pub fn valid_db_name(db: &str) -> bool {
    !db.is_empty()
        && db.len() <= 64
        && db
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-')
}

async fn run_client(
    paths: &Paths,
    name: &str,
    inst: &Instance,
    sql: &str,
) -> anyhow::Result<String> {
    use tokio::io::AsyncWriteExt;
    let dist = store::dist_dir(paths, inst.kind, &inst.version);
    // SQL goes over stdin, never argv, so secrets do not show up in `ps`.
    let mut child = tokio::process::Command::new(client(&dist))
        .arg(defaults_arg(paths, name))
        .args(["--batch", "--skip-column-names"])
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn()?;
    let mut stdin = child.stdin.take().expect("piped stdin");
    stdin.write_all(sql.as_bytes()).await?;
    stdin.write_all(b"\n").await?;
    drop(stdin);
    let out = child.wait_with_output().await?;
    if !out.status.success() {
        bail!("mysql: {}", String::from_utf8_lossy(&out.stderr).trim());
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

/// Make `root` usable over TCP from 127.0.0.1 with an empty password (what
/// Laravel's default `.env` expects). `--initialize-insecure` only creates
/// `root@localhost`, which TCP clients do not match under skip-name-resolve.
/// Idempotent; runs after every start over the unix socket.
pub async fn ensure_dev_accounts(paths: &Paths, name: &str, inst: &Instance) -> anyhow::Result<()> {
    run_client(
        paths,
        name,
        inst,
        "CREATE USER IF NOT EXISTS 'root'@'127.0.0.1' IDENTIFIED BY ''; \
         GRANT ALL PRIVILEGES ON *.* TO 'root'@'127.0.0.1' WITH GRANT OPTION;",
    )
    .await?;
    Ok(())
}

pub async fn create_database(
    paths: &Paths,
    name: &str,
    inst: &Instance,
    db: &str,
) -> anyhow::Result<()> {
    if !valid_db_name(db) {
        bail!("invalid database name {db:?}: use letters, digits, '_' and '-'");
    }
    run_client(
        paths,
        name,
        inst,
        &format!(
            "CREATE DATABASE IF NOT EXISTS `{db}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"
        ),
    )
    .await?;
    Ok(())
}

/// Quote a string literal for MySQL (NO_BACKSLASH_ESCAPES off, the default).
pub fn sql_string(v: &str) -> String {
    let mut out = String::with_capacity(v.len() + 2);
    out.push('\'');
    for c in v.chars() {
        match c {
            '\'' => out.push_str("''"),
            '\\' => out.push_str("\\\\"),
            '\0' => out.push_str("\\0"),
            c => out.push(c),
        }
    }
    out.push('\'');
    out
}

/// Valid MySQL account name (safe subset).
pub fn valid_user_name(u: &str) -> bool {
    !u.is_empty()
        && u.len() <= 32
        && u.bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-' || b == b'.')
}

/// Create (or update the password of) `user`@127.0.0.1 and @localhost with
/// full privileges on `db` only.
pub async fn ensure_app_user(
    paths: &Paths,
    name: &str,
    inst: &Instance,
    db: &str,
    user: &str,
    password: &str,
) -> anyhow::Result<()> {
    if !valid_db_name(db) {
        bail!("invalid database name {db:?}");
    }
    if !valid_user_name(user) || user == "root" {
        bail!("refusing to manage MySQL account {user:?}");
    }
    let pw = sql_string(password);
    let mut sql = String::new();
    for host in ["127.0.0.1", "localhost"] {
        sql.push_str(&format!(
            "CREATE USER IF NOT EXISTS '{user}'@'{host}' IDENTIFIED BY {pw}; \
             ALTER USER '{user}'@'{host}' IDENTIFIED BY {pw}; \
             GRANT ALL PRIVILEGES ON `{db}`.* TO '{user}'@'{host}'; "
        ));
    }
    run_client(paths, name, inst, &sql).await?;
    Ok(())
}

pub async fn list_databases(
    paths: &Paths,
    name: &str,
    inst: &Instance,
) -> anyhow::Result<Vec<String>> {
    const SYSTEM: &[&str] = &["information_schema", "mysql", "performance_schema", "sys"];
    Ok(run_client(paths, name, inst, "SHOW DATABASES")
        .await?
        .lines()
        .map(str::trim)
        .filter(|d| !d.is_empty() && !SYSTEM.contains(d))
        .map(str::to_owned)
        .collect())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::manifest::Kind;

    fn inst() -> Instance {
        Instance {
            kind: Kind::Mysql,
            version: "8.4.11".into(),
            port: 3307,
            enabled: true,
        }
    }

    #[test]
    fn option_file_is_local_only_and_quoted() {
        let p = Paths::at("/Users/me/Library/Application Support/Corral");
        let cnf = option_file(&p, "mysql", &inst());
        assert!(cnf.contains("bind-address=127.0.0.1"));
        assert!(cnf.contains("port=3307"));
        assert!(cnf.contains("mysqlx=OFF"));
        let client = cnf.split("[client]").nth(1).unwrap();
        assert!(
            client.contains("socket="),
            "client tools use the unix socket"
        );
        assert!(!client.contains("host="));
        assert!(cnf.contains(
            "datadir=\"/Users/me/Library/Application Support/Corral/services/data/mysql\""
        ));
        assert!(cnf.contains(
            "basedir=\"/Users/me/Library/Application Support/Corral/services/dist/mysql-8.4.11\""
        ));
    }

    #[test]
    fn spec_uses_defaults_file_first() {
        let t = tempfile::tempdir().unwrap();
        let p = Paths::at(t.path());
        let s = spec(&p, "mysql", &inst());
        assert!(s.args[0].starts_with("--defaults-file="));
        assert!(s.program.ends_with("services/dist/mysql-8.4.11/bin/mysqld"));
        assert_eq!(s.stop_timeout, Duration::from_secs(60));
    }

    #[test]
    fn sql_string_escapes() {
        assert_eq!(sql_string("plain"), "'plain'");
        assert_eq!(sql_string("it's"), "'it''s'");
        assert_eq!(sql_string("a\\b"), "'a\\\\b'");
        assert_eq!(
            sql_string("x'; DROP USER root; --"),
            "'x''; DROP USER root; --'"
        );
        assert!(valid_user_name("app_user"));
        assert!(!valid_user_name("x'@'%"));
    }

    #[test]
    fn db_names() {
        assert!(valid_db_name("el_billing"));
        assert!(valid_db_name("shop-2"));
        assert!(!valid_db_name("x`; DROP DATABASE mysql; --"));
        assert!(!valid_db_name(""));
        assert!(!valid_db_name(&"a".repeat(65)));
    }

    #[tokio::test]
    async fn refuses_to_initialize_over_foreign_data() {
        let t = tempfile::tempdir().unwrap();
        let p = Paths::at(t.path());
        let d = store::data_dir(&p, "mysql");
        std::fs::create_dir_all(&d).unwrap();
        std::fs::write(d.join("something"), "x").unwrap();
        let e = ensure_initialized(&p, "mysql", &inst()).await.unwrap_err();
        assert!(e.to_string().contains("not an initialized MySQL datadir"));
    }
}
